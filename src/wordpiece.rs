    #[cfg(not(target_arch = "wasm32"))]
    pub(crate) fn hf_content_ids(hf: &tokenizers::Tokenizer, text: &str) -> Vec<u32> {
        let enc = hf.encode(text, true).unwrap();
        let mask = enc.get_special_tokens_mask();
        enc.get_ids()
            .iter()
            .enumerate()
            .filter(|(i, _)| mask.get(*i).copied().unwrap_or(0) == 0)
            .map(|(_, &id)| id)
            .collect()
    }

