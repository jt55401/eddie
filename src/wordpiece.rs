//! A BERT WordPiece tokenizer for the query side of the sparse arm, built
//! from a `tokenizer.json` with `serde_json` alone.
//!
//! It reproduces what the `tokenizers` crate does for BERT-style files:
//! `BertNormalizer` (clean text, pad CJK characters with spaces, strip
//! accents, lowercase), `BertPreTokenizer` (split on whitespace, isolate
//! punctuation), greedy longest-match WordPiece with a `##` continuation
//! prefix, `[UNK]` for words that cannot be covered, and the
//! `max_input_chars_per_word` cap. Added tokens (`[SEP]`, `[MASK]`, ...)
//! typed literally in the text are matched before normalisation and encoded
//! to their ids, as the `tokenizers` crate does; the `[CLS]`/`[SEP]` a
//! post-processor would wrap around the sequence are never emitted (the
//! sparse query never scores them). Token ids therefore match the
//! `tokenizers` crate's `encode(text, true)` minus the tokens its
//! post-processor added; the native test
//! `matches_tokenizers_crate_on_real_vocab` checks 200 queries.
//!
//! The Unicode data it needs (canonical decompositions for accent
//! stripping, mark and punctuation categories) lives in
//! [`crate::wordpiece_tables`], generated by `scripts/gen_unicode_tables.py`,
//! so the lite WASM build does not carry the `unicode-normalization` tables.

use std::collections::HashMap;

use anyhow::{Context, Result, bail};
use serde_json::Value;

use crate::wordpiece_tables::{DECOMP_MULTI, DECOMP_SINGLE, MARKS, OTHER, PUNCT};

/// Fallback when `model.max_input_chars_per_word` is absent (HF default).
const DEFAULT_MAX_INPUT_CHARS: usize = 100;
/// Fallback when `model.continuing_subword_prefix` is absent (HF default).
const DEFAULT_PREFIX: &str = "##";

/// The basic-tokenizer flags of a `BertNormalizer`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Normalizer {
    pub clean_text: bool,
    pub handle_chinese_chars: bool,
    pub strip_accents: bool,
    pub lowercase: bool,
}

/// One entry of `added_tokens`: matched literally in the raw text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AddedToken {
    pub content: String,
    pub id: u32,
    pub special: bool,
}

/// Everything but the vocabulary: what an index stores next to the token
/// list in its `sparse/vocab` section so the runtime can rebuild the
/// tokenizer without `tokenizer.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WordPieceConfig {
    pub normalizer: Normalizer,
    pub unk_id: u32,
    /// `[CLS]` / `[SEP]` the post-processor adds (informational: the query
    /// side never emits them).
    pub cls_id: Option<u32>,
    pub sep_id: Option<u32>,
    pub max_input_chars: usize,
    /// Continuation prefix (`##`).
    pub prefix: String,
    pub added: Vec<AddedToken>,
    /// Content tokens kept per text.
    pub max_tokens: usize,
}

/// BERT WordPiece tokenizer (see the module docs).
#[derive(Debug, Clone)]
pub struct WordPiece {
    vocab: HashMap<String, u32>,
    /// Continuing tokens keyed without their prefix (`##ing` → `ing`).
    continuing: HashMap<String, u32>,
    unk_id: u32,
    cls_id: Option<u32>,
    sep_id: Option<u32>,
    max_input_chars: usize,
    prefix: String,
    normalizer: Normalizer,
    /// `added_tokens`, longest content first so overlapping matches prefer
    /// the longer token.
    added: Vec<AddedToken>,
    /// Content tokens kept per text (`max_seq_len` minus the special tokens
    /// the post-processor adds).
    max_tokens: usize,
}

impl WordPiece {
    /// Parse a `tokenizer.json`. `max_seq_len` is the encoder's sequence
    /// cap including special tokens (512 for BERT); it overrides the file's
    /// own `truncation` block like `prepare_tokenizer` does natively.
    pub fn from_tokenizer_json(bytes: &[u8], max_seq_len: usize) -> Result<Self> {
        let root: Value = serde_json::from_slice(bytes).context("parsing tokenizer.json")?;
        let model = root
            .get("model")
            .filter(|m| m.is_object())
            .context("tokenizer.json has no model object")?;
        let model_type = model.get("type").and_then(Value::as_str).unwrap_or("");
        if model_type != "WordPiece" {
            bail!(
                "tokenizer.json model type {:?} is not WordPiece",
                model_type
            );
        }
        let vocab_json = model
            .get("vocab")
            .and_then(Value::as_object)
            .context("tokenizer.json model has no vocab object")?;
        let prefix = model
            .get("continuing_subword_prefix")
            .and_then(Value::as_str)
            .unwrap_or(DEFAULT_PREFIX);
        let mut vocab = HashMap::with_capacity(vocab_json.len());
        for (token, id) in vocab_json {
            let id = id
                .as_u64()
                .and_then(|v| u32::try_from(v).ok())
                .with_context(|| format!("vocab entry {:?} has no u32 id", token))?;
            vocab.insert(token.clone(), id);
        }
        let unk_token = model
            .get("unk_token")
            .and_then(Value::as_str)
            .unwrap_or("[UNK]");
        let unk_id = *vocab
            .get(unk_token)
            .with_context(|| format!("unk_token {:?} is not in the vocab", unk_token))?;
        let max_input_chars = model
            .get("max_input_chars_per_word")
            .and_then(Value::as_u64)
            .map(|v| v as usize)
            .unwrap_or(DEFAULT_MAX_INPUT_CHARS);

        let normalizer = parse_normalizer(root.get("normalizer"))?;
        check_pre_tokenizer(root.get("pre_tokenizer"))?;
        let specials_added = post_processor_special_count(root.get("post_processor"));
        let (cls_id, sep_id) = post_processor_cls_sep(root.get("post_processor"), &vocab);

        let added: Vec<AddedToken> = root
            .get("added_tokens")
            .and_then(Value::as_array)
            .map(|list| {
                list.iter()
                    .filter_map(|t| {
                        let content = t.get("content")?.as_str()?;
                        let id = u32::try_from(t.get("id")?.as_u64()?).ok()?;
                        let special = t.get("special").and_then(Value::as_bool).unwrap_or(false);
                        (!content.is_empty()).then(|| AddedToken {
                            content: content.to_string(),
                            id,
                            special,
                        })
                    })
                    .collect()
            })
            .unwrap_or_default();

        Self::assemble(
            vocab,
            WordPieceConfig {
                normalizer,
                unk_id,
                cls_id,
                sep_id,
                max_input_chars,
                prefix: prefix.to_string(),
                added,
                max_tokens: max_seq_len.max(1).saturating_sub(specials_added).max(1),
            },
        )
    }

    /// Rebuild a tokenizer from its vocabulary in id order (an empty string
    /// marks an unused id) and its config, as stored in an index's
    /// `sparse/vocab` section.
    pub fn from_vocab(tokens: Vec<String>, config: WordPieceConfig) -> Result<Self> {
        let mut vocab = HashMap::with_capacity(tokens.len());
        for (id, token) in tokens.into_iter().enumerate() {
            if token.is_empty() {
                continue;
            }
            let id = u32::try_from(id).context("vocab has more than u32::MAX entries")?;
            vocab.insert(token, id);
        }
        Self::assemble(vocab, config)
    }

    /// The vocabulary in id order (gaps as empty strings) and the config:
    /// the inverse of [`WordPiece::from_vocab`].
    pub fn to_vocab(&self) -> (Vec<String>, WordPieceConfig) {
        let max_id = self
            .vocab
            .values()
            .copied()
            .max()
            .map_or(0, |m| m as usize + 1);
        let mut tokens = vec![String::new(); max_id];
        for (token, &id) in &self.vocab {
            tokens[id as usize] = token.clone();
        }
        let mut added = self.added.clone();
        added.sort_by_key(|t| t.id);
        (
            tokens,
            WordPieceConfig {
                normalizer: self.normalizer,
                unk_id: self.unk_id,
                cls_id: self.cls_id,
                sep_id: self.sep_id,
                max_input_chars: self.max_input_chars,
                prefix: self.prefix.clone(),
                added,
                max_tokens: self.max_tokens,
            },
        )
    }

    fn assemble(vocab: HashMap<String, u32>, config: WordPieceConfig) -> Result<Self> {
        let mut continuing = HashMap::new();
        if !config.prefix.is_empty() {
            for (token, &id) in &vocab {
                if let Some(rest) = token.strip_prefix(config.prefix.as_str())
                    && !rest.is_empty()
                {
                    continuing.insert(rest.to_string(), id);
                }
            }
        }
        if !vocab.values().any(|&id| id == config.unk_id) {
            bail!("unk id {} is not in the vocab", config.unk_id);
        }
        let mut added = config.added;
        added.retain(|t| !t.content.is_empty());
        added.sort_by_key(|t| std::cmp::Reverse(t.content.len()));
        Ok(Self {
            vocab,
            continuing,
            unk_id: config.unk_id,
            cls_id: config.cls_id,
            sep_id: config.sep_id,
            max_input_chars: config.max_input_chars,
            prefix: config.prefix,
            normalizer: config.normalizer,
            added,
            max_tokens: config.max_tokens.max(1),
        })
    }

    /// Id of a vocabulary token (exact string, including any `##` prefix).
    pub fn token_to_id(&self, token: &str) -> Option<u32> {
        self.vocab.get(token).copied()
    }

    pub fn vocab_size(&self) -> usize {
        self.vocab.len()
    }

    /// Ids of the special tokens (`added_tokens` flagged `special`).
    pub fn special_ids(&self) -> Vec<u32> {
        let mut ids: Vec<u32> = self
            .added
            .iter()
            .filter(|t| t.special)
            .map(|t| t.id)
            .collect();
        ids.sort_unstable();
        ids.dedup();
        ids
    }

    /// Token ids of `text` in order (no post-processor `[CLS]`/`[SEP]`),
    /// truncated to the sequence cap.
    pub fn encode(&self, text: &str) -> Vec<u32> {
        let mut ids = Vec::new();
        for piece in self.split_added(text) {
            match piece {
                Piece::Added(tok) => ids.push(tok.id),
                Piece::Text(raw) => {
                    let normalized = self.normalize(raw);
                    for word in pre_tokenize(&normalized) {
                        self.word_pieces(word, &mut ids);
                    }
                }
            }
            if ids.len() >= self.max_tokens {
                break;
            }
        }
        ids.truncate(self.max_tokens);
        ids
    }

    /// Split the raw text on literal occurrences of the added tokens.
    fn split_added<'a>(&'a self, text: &'a str) -> Vec<Piece<'a>> {
        let mut out = Vec::new();
        if self.added.is_empty() {
            out.push(Piece::Text(text));
            return out;
        }
        let mut rest = text;
        while !rest.is_empty() {
            let mut best: Option<(usize, &AddedToken)> = None;
            for tok in &self.added {
                if let Some(pos) = rest.find(tok.content.as_str())
                    && best.is_none_or(|(p, _)| pos < p)
                {
                    best = Some((pos, tok));
                }
            }
            match best {
                Some((pos, tok)) => {
                    if pos > 0 {
                        out.push(Piece::Text(&rest[..pos]));
                    }
                    out.push(Piece::Added(tok));
                    rest = &rest[pos + tok.content.len()..];
                }
                None => {
                    out.push(Piece::Text(rest));
                    break;
                }
            }
        }
        out
    }

    /// `BertNormalizer`, in its order: clean text, pad CJK characters,
    /// strip accents, lowercase.
    fn normalize(&self, text: &str) -> String {
        let n = &self.normalizer;
        let mut s: String = if n.clean_text {
            text.chars()
                .filter(|&c| c != '\0' && c != '\u{fffd}' && !is_control(c))
                .map(|c| if c.is_whitespace() { ' ' } else { c })
                .collect()
        } else {
            text.to_string()
        };
        if n.handle_chinese_chars {
            let mut padded = String::with_capacity(s.len() + 8);
            for c in s.chars() {
                if is_chinese_char(c) {
                    padded.push(' ');
                    padded.push(c);
                    padded.push(' ');
                } else {
                    padded.push(c);
                }
            }
            s = padded;
        }
        if n.strip_accents {
            let mut stripped = String::with_capacity(s.len());
            for c in s.chars() {
                push_base_chars(c, &mut stripped);
            }
            s = stripped;
        }
        if n.lowercase {
            s = s.chars().flat_map(char::to_lowercase).collect();
        }
        s
    }

    /// Greedy longest-match WordPiece of one pre-token.
    fn word_pieces(&self, word: &str, out: &mut Vec<u32>) {
        if word.chars().count() > self.max_input_chars {
            out.push(self.unk_id);
            return;
        }
        let mut pieces = Vec::new();
        let mut start = 0usize;
        while start < word.len() {
            let mut end = word.len();
            let mut found = None;
            while start < end {
                let sub = &word[start..end];
                let hit = if start == 0 {
                    self.vocab.get(sub)
                } else {
                    self.continuing.get(sub)
                };
                if let Some(&id) = hit {
                    found = Some(id);
                    break;
                }
                end -= sub.chars().next_back().map_or(1, char::len_utf8);
            }
            match found {
                Some(id) => {
                    pieces.push(id);
                    start = end;
                }
                None => {
                    out.push(self.unk_id);
                    return;
                }
            }
        }
        out.extend(pieces);
    }
}

enum Piece<'a> {
    Text(&'a str),
    Added(&'a AddedToken),
}

fn parse_normalizer(value: Option<&Value>) -> Result<Normalizer> {
    let mut n = Normalizer {
        clean_text: false,
        handle_chinese_chars: false,
        strip_accents: false,
        lowercase: false,
    };
    fn apply(n: &mut Normalizer, v: &Value) -> Result<()> {
        let kind = v.get("type").and_then(Value::as_str).unwrap_or("");
        let flag =
            |name: &str, default: bool| v.get(name).and_then(Value::as_bool).unwrap_or(default);
        match kind {
            "BertNormalizer" => {
                n.clean_text = flag("clean_text", true);
                n.handle_chinese_chars = flag("handle_chinese_chars", true);
                n.lowercase = flag("lowercase", true);
                // HF: `strip_accents` null means "same as lowercase".
                n.strip_accents = match v.get("strip_accents") {
                    Some(Value::Bool(b)) => *b,
                    _ => n.lowercase,
                };
            }
            "Lowercase" => n.lowercase = true,
            "StripAccents" => n.strip_accents = true,
            "Sequence" => {
                for step in v
                    .get("normalizers")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                {
                    apply(n, step)?;
                }
            }
            other => bail!(
                "tokenizer.json normalizer {:?} is not supported (expected BertNormalizer)",
                other
            ),
        }
        Ok(())
    }
    match value {
        None | Some(Value::Null) => {}
        Some(v) => apply(&mut n, v)?,
    }
    Ok(n)
}

fn check_pre_tokenizer(value: Option<&Value>) -> Result<()> {
    let kind = value
        .and_then(|v| v.get("type"))
        .and_then(Value::as_str)
        .unwrap_or("");
    if kind != "BertPreTokenizer" {
        bail!(
            "tokenizer.json pre_tokenizer {:?} is not supported (expected BertPreTokenizer)",
            kind
        );
    }
    Ok(())
}

/// The `[CLS]` / `[SEP]` ids a post-processor wraps around a sequence.
fn post_processor_cls_sep(
    value: Option<&Value>,
    vocab: &HashMap<String, u32>,
) -> (Option<u32>, Option<u32>) {
    let Some(v) = value else { return (None, None) };
    let pair_id = |key: &str| {
        v.get(key)
            .and_then(Value::as_array)
            .and_then(|pair| pair.get(1))
            .and_then(Value::as_u64)
            .and_then(|id| u32::try_from(id).ok())
    };
    match v.get("type").and_then(Value::as_str).unwrap_or("") {
        "BertProcessing" | "RobertaProcessing" => (pair_id("cls"), pair_id("sep")),
        "TemplateProcessing" => {
            let special_id = |name: &str| {
                v.get("special_tokens")
                    .and_then(|s| s.get(name))
                    .and_then(|s| s.get("ids"))
                    .and_then(Value::as_array)
                    .and_then(|ids| ids.first())
                    .and_then(Value::as_u64)
                    .and_then(|id| u32::try_from(id).ok())
                    .or_else(|| vocab.get(name).copied())
            };
            (special_id("[CLS]"), special_id("[SEP]"))
        }
        _ => (None, None),
    }
}

/// Special tokens the post-processor adds around a single sequence: they
/// count against the sequence cap the way HF truncation does.
fn post_processor_special_count(value: Option<&Value>) -> usize {
    let Some(v) = value else { return 0 };
    match v.get("type").and_then(Value::as_str).unwrap_or("") {
        "BertProcessing" | "RobertaProcessing" => 2,
        "TemplateProcessing" => v
            .get("single")
            .and_then(Value::as_array)
            .map(|steps| {
                steps
                    .iter()
                    .filter(|s| s.get("SpecialToken").is_some())
                    .count()
            })
            .unwrap_or(0),
        _ => 0,
    }
}

/// `BertPreTokenizer`: whitespace-separated words with every punctuation
/// character isolated as its own word.
fn pre_tokenize(text: &str) -> Vec<&str> {
    let mut words = Vec::new();
    let mut start: Option<usize> = None;
    for (i, c) in text.char_indices() {
        if c.is_whitespace() {
            if let Some(s) = start.take() {
                words.push(&text[s..i]);
            }
        } else if is_bert_punctuation(c) {
            if let Some(s) = start.take() {
                words.push(&text[s..i]);
            }
            words.push(&text[i..i + c.len_utf8()]);
        } else if start.is_none() {
            start = Some(i);
        }
    }
    if let Some(s) = start {
        words.push(&text[s..]);
    }
    words
}

/// `tokenizers`' notion of a control character: general category C*
/// (control, format, unassigned, private use), except the tab and line
/// breaks it counts as whitespace. Zero-width and soft-hyphen format
/// characters are deleted, not split on.
fn is_control(c: char) -> bool {
    if matches!(c, '\t' | '\n' | '\r') {
        return false;
    }
    if c.is_ascii() {
        return c.is_ascii_control();
    }
    in_ranges(OTHER, c)
}

fn is_chinese_char(c: char) -> bool {
    matches!(
        c as u32,
        0x4E00..=0x9FFF
            | 0x3400..=0x4DBF
            | 0x20000..=0x2A6DF
            | 0x2A700..=0x2B73F
            | 0x2B740..=0x2B81F
            | 0x2B920..=0x2CEAF
            | 0xF900..=0xFAFF
            | 0x2F800..=0x2FA1F
    )
}

fn in_ranges(ranges: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    let idx = ranges.partition_point(|&(_, hi)| hi < cp);
    ranges.get(idx).is_some_and(|&(lo, _)| lo <= cp)
}

fn is_combining_mark(c: char) -> bool {
    in_ranges(MARKS, c)
}

fn is_bert_punctuation(c: char) -> bool {
    c.is_ascii_punctuation() || (!c.is_ascii() && in_ranges(PUNCT, c))
}

/// NFD-decompose `c` and push the characters that are not combining marks
/// (HF `do_strip_accents`).
fn push_base_chars(c: char, out: &mut String) {
    if is_combining_mark(c) {
        return;
    }
    let cp = c as u32;
    if let (0xAC00..=0xD7A3, Some(s)) = (cp, hangul_jamo(cp)) {
        out.push_str(&s);
        return;
    }
    if let Ok(i) = DECOMP_SINGLE.binary_search_by_key(&cp, |&(from, _)| from) {
        if let Some(base) = char::from_u32(DECOMP_SINGLE[i].1) {
            out.push(base);
        }
        return;
    }
    if let Ok(i) = DECOMP_MULTI.binary_search_by_key(&cp, |&(from, _)| from) {
        out.push_str(DECOMP_MULTI[i].1);
        return;
    }
    out.push(c);
}

/// Algorithmic decomposition of a precomposed Hangul syllable into its
/// leading, vowel and (optional) trailing jamo.
fn hangul_jamo(cp: u32) -> Option<String> {
    const S_BASE: u32 = 0xAC00;
    const L_BASE: u32 = 0x1100;
    const V_BASE: u32 = 0x1161;
    const T_BASE: u32 = 0x11A7;
    const T_COUNT: u32 = 28;
    const N_COUNT: u32 = 21 * T_COUNT;
    let s = cp.checked_sub(S_BASE)?;
    if s >= 19 * N_COUNT {
        return None;
    }
    let l = char::from_u32(L_BASE + s / N_COUNT)?;
    let v = char::from_u32(V_BASE + (s % N_COUNT) / T_COUNT)?;
    let t = s % T_COUNT;
    let mut out = String::with_capacity(9);
    out.push(l);
    out.push(v);
    if t != 0 {
        out.push(char::from_u32(T_BASE + t)?);
    }
    Some(out)
}

