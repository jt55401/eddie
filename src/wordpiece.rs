    /// Parity with the `tokenizers` crate on the real sparse vocabulary
    /// (200+ queries). Needs the model in the HuggingFace cache:
    /// `cargo test -- --ignored matches_tokenizers_crate_on_real_vocab`.
    #[cfg(not(target_arch = "wasm32"))]
    #[test]
    #[ignore] // requires network access or the HuggingFace cache
    fn matches_tokenizers_crate_on_real_vocab() {
        let repo =
            crate::embed::hub::ModelRepo::open(crate::models::DEFAULT_SPARSE_MODEL, None).unwrap();
        let bytes = std::fs::read(repo.get("tokenizer.json").unwrap()).unwrap();
        let ours = WordPiece::from_tokenizer_json(&bytes, 512).unwrap();
        let mut hf = tokenizers::Tokenizer::from_bytes(&bytes).unwrap();
        crate::embed::prepare_tokenizer(&mut hf, 512).unwrap();
        let mut queries: Vec<String> = Vec::new();
        queries.push("x".repeat(101));
        for seed in PARITY_SEEDS {
            queries.push(seed.to_string());
            queries.push(seed.to_uppercase());
            queries.push(format!("«{}»? Ça va… {}!", seed, seed.len()));
        }
        assert!(queries.len() >= 200, "{} queries", queries.len());
        let (vocab_tokens, config) = ours.to_vocab();
        let rebuilt = WordPiece::from_vocab(vocab_tokens, config).unwrap();
        let mut tokens = 0usize;
        for q in &queries {
            let expected = hf_content_ids(&hf, q);
            let got = ours.encode(q);
            tokens += expected.len();
            assert_eq!(got, expected, "query {:?}", q);
            assert_eq!(
                rebuilt.encode(q),
                expected,
                "rebuilt tokenizer, query {:?}",
                q
            );
        }
        eprintln!(
            "wordpiece parity: {} queries, {} tokens, all ids identical",
            queries.len(),
            tokens
        );
    }
